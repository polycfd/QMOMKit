double tolerance_for(const std::size_t n)
{
    if (n <= 7)
    {
        return 1.0e-12;
    }
    return n == 8 ? 1.0e-11 : 5.0e-10;
}

void verify_against_references(const std::vector<HyperbolicReference>& references)
{
    qmomkit::WheelerOptions fixed;
    fixed.adaptive = false;
    for (const HyperbolicReference& reference : references)
    {
        const std::size_t nodes = reference.n + 1;
        const qmomkit::MomentSet moments(reference.moments);
        const qmomkit::Quadrature1D rule = qmomkit::internal::compute_hyperbolic_quadrature(moments, reference.n, fixed);
        QMOMKIT_VERIFY_CHECK(rule.ok());
        QMOMKIT_VERIFY_CHECK(rule.abscissas.size() == nodes && rule.weights.size() == nodes);

        double position_scale = 0.0;
        double total_weight = 0.0;
        for (std::size_t i = 0; i < nodes; ++i)
        {
            position_scale = std::max(position_scale, std::abs(reference.abscissas[i]));
            total_weight += reference.weights[i];
        }
        const double tolerance = tolerance_for(reference.n);
        for (std::size_t i = 0; i < nodes; ++i)
        {
            QMOMKIT_VERIFY_NEAR(rule.abscissas[i], reference.abscissas[i], tolerance * position_scale);
            QMOMKIT_VERIFY_NEAR(rule.weights[i], reference.weights[i], tolerance * total_weight);
        }

        const qmomkit::Quadrature1D adaptive = qmomkit::internal::compute_hyperbolic_quadrature(moments, reference.n, {});
        QMOMKIT_VERIFY_CHECK(adaptive.status == rule.status && adaptive.abscissas == rule.abscissas && adaptive.weights == rule.weights);
    }
}

void test_symmetric()
{
    verify_against_references(symmetric_references);
}

void test_skewed()
{
    verify_against_references(skewed_references);
}

void test_bimodal()
{
    verify_against_references(bimodal_references);
}

